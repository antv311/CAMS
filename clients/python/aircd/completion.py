"""Shell completion scripts for the ``airc`` CLI.

``airc completion bash|zsh|powershell`` prints a script that completes
subcommands, options and fixed option values.  The scripts are generated
from the live argparse tree, so they never drift from the parser: add a
subcommand or a ``choices=`` option and the next generated script knows it.

Each command is identified by its path, starting with ``airc``:
``"airc"``, ``"airc task"``, ``"airc task status"``.  For every path the
generator records

* ``subs``  - subcommand names,
* ``opts``  - option strings (``--note``, ``-o``, ...),
* ``vals``  - options that take a value, keyed ``"<path>|<option>"``, with
  their fixed choices (empty when the value is free text or a file),
* ``pos``   - words the Nth positional argument accepts, keyed
  ``"<path>@<N>"`` (N counts from 0; argparse ``choices`` plus the hints in
  ``POSITIONAL_HINTS``).
"""

from __future__ import annotations

import argparse
import re
from dataclasses import dataclass, field

SHELLS = ("bash", "zsh", "powershell")

# Positional arguments the parser leaves open (the hub validates them) but
# whose usual values are worth offering.  Keyed "<command path>@<index>".
POSITIONAL_HINTS: dict[str, tuple[str, ...]] = {
    "airc task status@1": ("in_progress", "testing", "review", "changes_requested", "merged", "cancelled"),
}

# Only plain words go into the generated scripts; anything else (spaces,
# quotes, shell metacharacters) is dropped rather than escaped per shell.
_SAFE_WORD = re.compile(r"^[A-Za-z0-9_.:/@#%+,=-]+$")


@dataclass
class CompletionTree:
    subs: dict[str, list[str]] = field(default_factory=dict)
    opts: dict[str, list[str]] = field(default_factory=dict)
    vals: dict[str, list[str]] = field(default_factory=dict)
    pos: dict[str, list[str]] = field(default_factory=dict)


def _words(items) -> list[str]:
    out: list[str] = []
    for item in items:
        word = str(item)
        if _SAFE_WORD.match(word) and word not in out:
            out.append(word)
    return out


def build_tree(parser: argparse.ArgumentParser, root: str = "airc") -> CompletionTree:
    tree = CompletionTree()
    _walk(parser, root, tree)
    return tree


def _walk(parser: argparse.ArgumentParser, path: str, tree: CompletionTree) -> None:
    subs: list[str] = []
    opts: list[str] = []
    index = 0
    children: list[tuple[str, argparse.ArgumentParser]] = []
    for action in parser._actions:
        if isinstance(action, argparse._SubParsersAction):
            for name, child in action.choices.items():
                subs.append(name)
                children.append((name, child))
        elif action.option_strings:
            if action.help == argparse.SUPPRESS:
                continue
            opts.extend(action.option_strings)
            if action.nargs != 0:
                choices = _words(action.choices or ())
                for opt in action.option_strings:
                    tree.vals[f"{path}|{opt}"] = choices
        else:
            key = f"{path}@{index}"
            words = list(action.choices or ()) + list(POSITIONAL_HINTS.get(key, ()))
            if words:
                tree.pos[key] = _words(words)
            index += 1
    tree.subs[path] = _words(subs)
    tree.opts[path] = _words(opts)
    for name, child in children:
        _walk(child, f"{path} {name}", tree)


# ── bash ───────────────────────────────────────────────────────


def _bash_case(func: str, table: dict[str, list[str]], doc: str) -> str:
    lines = [f"# {doc}", f"{func}() {{", '    case "$1" in']
    for key in sorted(table):
        if table[key]:
            lines.append(f"        \"{key}\") echo \"{' '.join(table[key])}\" ;;")
    lines += ["    esac", "}"]
    return "\n".join(lines)


def render_bash(tree: CompletionTree) -> str:
    vals_lines = [
        "# Prints the fixed values of option $2 under command path $1.",
        "# Returns 1 when that option takes no value.",
        "_airc_vals() {",
        '    case "$1|$2" in',
    ]
    for key in sorted(tree.vals):
        choices = " ".join(tree.vals[key])
        body = f'echo "{choices}"; return 0' if choices else "return 0"
        vals_lines.append(f'        "{key}") {body} ;;')
    vals_lines += ["    esac", "    return 1", "}"]
    return "\n".join(
        [
            "# bash completion for airc. Generated by `airc completion bash`.",
            "# Load it now:      eval \"$(airc completion bash)\"",
            "# Load it always:   airc completion bash > ~/.local/share/bash-completion/completions/airc",
            "",
            _bash_case("_airc_subs", tree.subs, "Subcommands of command path $1."),
            "",
            _bash_case("_airc_opts", tree.opts, "Options of command path $1."),
            "",
            _bash_case("_airc_pos", tree.pos, "Fixed values of positional argument \"<path>@<index>\" $1."),
            "",
            "\n".join(vals_lines),
            "",
            _BASH_MAIN,
        ]
    ) + "\n"


_BASH_MAIN = r"""_airc() {
    local cur="${COMP_WORDS[COMP_CWORD]}" prev="" cmdpath="airc" w subs choices i=1 npos=0
    COMPREPLY=()
    while [ "$i" -lt "$COMP_CWORD" ]; do
        w="${COMP_WORDS[i]}"
        if [[ "$w" == -* ]]; then
            # Skip the value of an option that takes one (unless given as --opt=value).
            if [[ "$w" != *=* ]] && _airc_vals "$cmdpath" "$w" >/dev/null; then
                i=$((i + 1))
            fi
        else
            subs=" $(_airc_subs "$cmdpath") "
            if [[ "$subs" == *" $w "* ]]; then
                cmdpath="$cmdpath $w"
                npos=0
            else
                npos=$((npos + 1))
            fi
        fi
        i=$((i + 1))
    done
    if [ "$COMP_CWORD" -gt 1 ]; then
        prev="${COMP_WORDS[COMP_CWORD-1]}"
    fi
    if [[ "$prev" == -* ]] && choices="$(_airc_vals "$cmdpath" "$prev")"; then
        if [ -n "$choices" ]; then
            COMPREPLY=($(compgen -W "$choices" -- "$cur"))
        else
            COMPREPLY=($(compgen -f -- "$cur"))
        fi
        return 0
    fi
    if [[ "$cur" == -* ]]; then
        COMPREPLY=($(compgen -W "$(_airc_opts "$cmdpath")" -- "$cur"))
    else
        COMPREPLY=($(compgen -W "$(_airc_subs "$cmdpath") $(_airc_pos "$cmdpath@$npos")" -- "$cur"))
    fi
    return 0
}

complete -o default -F _airc airc airc.exe"""


# ── zsh ────────────────────────────────────────────────────────


def _zsh_assoc(name: str, table: dict[str, list[str]], keep_empty: bool = False) -> str:
    lines = [f"    local -A {name}", f"    {name}=("]
    for key in sorted(table):
        if table[key] or keep_empty:
            lines.append(f"        '{key}' '{' '.join(table[key])}'")
    lines.append("    )")
    return "\n".join(lines)


def render_zsh(tree: CompletionTree) -> str:
    return "\n".join(
        [
            "#compdef airc",
            "# zsh completion for airc. Generated by `airc completion zsh`.",
            "# Load it now:      eval \"$(airc completion zsh)\"   (after compinit)",
            "# Load it always:   airc completion zsh > \"${fpath[1]}/_airc\"",
            "",
            "_airc() {",
            _zsh_assoc("subs", tree.subs),
            _zsh_assoc("opts", tree.opts),
            _zsh_assoc("pos", tree.pos),
            "    # Options that take a value -> their fixed choices ('' = free text or file).",
            _zsh_assoc("vals", tree.vals, keep_empty=True),
            _ZSH_MAIN,
        ]
    ) + "\n"


_ZSH_MAIN = r"""    local cmdpath="airc" w prev="" i npos=0
    local -a sublist
    for (( i = 2; i < CURRENT; i++ )); do
        w="${words[i]}"
        if [[ "$w" == -* ]]; then
            if [[ "$w" != *=* ]] && (( ${+vals[$cmdpath|$w]} )); then
                (( i++ ))
            fi
        else
            sublist=(${=subs[$cmdpath]})
            if (( ${sublist[(Ie)$w]} )); then
                cmdpath="$cmdpath $w"
                npos=0
            else
                (( npos++ ))
            fi
        fi
    done
    (( CURRENT > 2 )) && prev="${words[CURRENT-1]}"
    if [[ "$prev" == -* ]] && (( ${+vals[$cmdpath|$prev]} )); then
        if [[ -n "${vals[$cmdpath|$prev]}" ]]; then
            compadd -- ${=vals[$cmdpath|$prev]}
        else
            _files
        fi
        return
    fi
    if [[ "${words[CURRENT]}" == -* ]]; then
        compadd -- ${=opts[$cmdpath]}
    elif [[ -n "${subs[$cmdpath]}${pos[$cmdpath@$npos]}" ]]; then
        compadd -- ${=subs[$cmdpath]} ${=pos[$cmdpath@$npos]}
    else
        _files
    fi
}

if [[ "${funcstack[1]}" == "_airc" ]]; then
    _airc "$@"
else
    compdef _airc airc
fi"""


# ── PowerShell ─────────────────────────────────────────────────


def _ps_table(name: str, table: dict[str, list[str]], keep_empty: bool = False) -> str:
    lines = [f"    ${name} = @{{"]
    for key in sorted(table):
        if table[key] or keep_empty:
            items = ", ".join(f"'{w}'" for w in table[key])
            lines.append(f"        '{key}' = @({items})")
    lines.append("    }")
    return "\n".join(lines)


def render_powershell(tree: CompletionTree) -> str:
    return "\n".join(
        [
            "# PowerShell completion for airc. Generated by `airc completion powershell`.",
            "# Load it now:      airc completion powershell | Out-String | Invoke-Expression",
            "# Load it always:   add that line to $PROFILE",
            "",
            "Register-ArgumentCompleter -Native -CommandName @('airc', 'airc.exe', 'airc.cmd') -ScriptBlock {",
            "    param($wordToComplete, $commandAst, $cursorPosition)",
            _ps_table("subs", tree.subs),
            _ps_table("opts", tree.opts),
            _ps_table("pos", tree.pos),
            "    # Options that take a value -> their fixed choices (empty = free text or file).",
            _ps_table("vals", tree.vals, keep_empty=True),
            _PS_MAIN,
        ]
    ) + "\n"


_PS_MAIN = r"""    $before = @($commandAst.CommandElements |
        Select-Object -Skip 1 |
        Where-Object { $_.Extent.EndOffset -lt $cursorPosition } |
        ForEach-Object { $_.Extent.Text })
    $cmdpath = 'airc'
    $skip = $false
    $npos = 0
    foreach ($w in $before) {
        if ($skip) { $skip = $false; continue }
        if ($w.StartsWith('-')) {
            if (-not $w.Contains('=') -and $vals.ContainsKey("$cmdpath|$w")) { $skip = $true }
        } elseif ($subs.ContainsKey($cmdpath) -and ($subs[$cmdpath] -ccontains $w)) {
            $cmdpath = "$cmdpath $w"
            $npos = 0
        } else {
            $npos++
        }
    }
    $prev = if ($before.Count -gt 0) { $before[-1] } else { '' }
    if ($skip) {
        $candidates = @($vals["$cmdpath|$prev"])
        # No fixed values: return nothing so PowerShell falls back to paths.
        if ($candidates.Count -eq 0) { return }
    } elseif ($wordToComplete.StartsWith('-')) {
        $candidates = @($opts[$cmdpath])
    } else {
        $candidates = @($subs[$cmdpath]) + @($pos["$cmdpath@$npos"])
    }
    $candidates |
        Where-Object { $_ -and $_.StartsWith($wordToComplete, [System.StringComparison]::OrdinalIgnoreCase) } |
        ForEach-Object { [System.Management.Automation.CompletionResult]::new($_, $_, 'ParameterValue', $_) }
}"""


RENDERERS = {"bash": render_bash, "zsh": render_zsh, "powershell": render_powershell}


def render(shell: str, parser: argparse.ArgumentParser) -> str:
    try:
        renderer = RENDERERS[shell]
    except KeyError:
        raise ValueError(f"unsupported shell {shell!r}; choose one of {', '.join(SHELLS)}") from None
    return renderer(build_tree(parser))
